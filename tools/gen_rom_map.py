"""Generates the header with where the plugin patches the ROM image (D36): file offsets of the DAC
sample table and of the end of the used image, from the ROM build's symbol.txt, and the names of
the ROM's samples by note, from its pcm_sample.c. Run by tools/build_plugin.sh after every ROM build,
because every change of the ROM moves them. Fails when a symbol is missing.

usage: gen_rom_map.py <out/symbol.txt> <src/pcm_sample.c> <rom_map.h>
"""
import re
import sys

RAM = 0xE0FF0000


def main():
    symbols_path, samples_path, output = sys.argv[1:4]
    symbols = {}
    for line in open(symbols_path):
        parts = line.split()
        if len(parts) == 3:
            # Link-time optimization may add a suffix to a local name.
            symbols.setdefault(parts[2].split(".")[0], int(parts[0], 16))
    for name in ("_stext", "_edata", "percussionPcmSample"):
        if name not in symbols:
            raise SystemExit(f"{symbols_path}: no symbol {name}")
    # SGDK copies .data from the image at _stext to RAM at start, so the file holds the table there.
    data_load = symbols["_stext"]
    table = symbols["percussionPcmSample"]
    if not RAM <= table < symbols["_edata"]:
        raise SystemExit(f"percussionPcmSample at {table:#x} is not in .data")

    text = open(samples_path).read()
    files = dict(re.findall(r"static const PcmSample (\w+) = \{ pcm_(\w+),", text))
    body = re.search(r"percussionPcmSample\[128\]\s*=\s*\{(.*?)\};", text, re.S).group(1)
    body = re.sub(r"//[^\n]*", "", body)
    entries = [e.strip() for e in body.split(",") if e.strip()]
    if len(entries) != 128:
        raise SystemExit(f"expected 128 notes in percussionPcmSample, found {len(entries)}")
    names = []
    for entry in entries:
        if entry == "NULL":
            names.append("")
        else:
            names.append(files[entry.lstrip("&")].replace("_", ""))

    lines = [
        "// Generated by tools/gen_rom_map.py from the ROM build. Do not edit.",
        "#ifndef MDMI_ROM_MAP_H",
        "#define MDMI_ROM_MAP_H",
        f"#define ROM_PCM_TABLE 0x{data_load + table - RAM:06X}u",
        f"#define ROM_USED_END 0x{data_load + symbols['_edata'] - RAM:06X}u",
        "static const char *const ROM_SAMPLE_NAMES[128] = {",
    ]
    for i in range(0, 128, 8):
        lines.append("\t" + " ".join(f'"{n}",' for n in names[i:i + 8]))
    lines += ["};", "#endif", ""]
    open(output, "w", newline="\n").write("\n".join(lines))


if __name__ == "__main__":
    main()
