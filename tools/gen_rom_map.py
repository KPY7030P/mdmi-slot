"""Generates the header with where the plugin patches the ROM image (D36): file offsets of the DAC
sample table and of the end of the used image, from the ROM build's symbol.txt, and the names of
the ROM's samples by note, from its pcm_sample.c. Run by tools/build_plugin.sh after every ROM build,
because every change of the ROM moves them. Fails when a symbol is missing.

usage: gen_rom_map.py <out/symbol.txt> <src/pcm_sample.c> <rom_map.h>
"""
import re
import sys

RAM = 0xE0FF0000
STATS = ("ui_stat_lines", "ui_stat_lines_max", "ui_stat_ambig", "ui_stat_words", "ui_stat_words_max",
         "ui_stat_lag", "ui_stat_lag_max", "ui_stat_late_notes", "ui_stat_frames", "ui_stat_missed",
         "ui_stat_draw_lines", "ui_stat_draw_lines_max", "ui_stat_parts", "ui_stat_calib", "ui_stat_draw_sum", "ui_test_off",
         "ui_stat_vint_words_max", "ui_stat_vint_lines_max", "ui_stat_vdp_outside", "ui_stat_vint_late", "ui_shadow", "ui_stat_parts_sum", "ui_stat_curve_lag_max", "ui_stat_vint_lines_count")


def main():
    symbols_path, samples_path, output = sys.argv[1:4]
    symbols = {}
    for line in open(symbols_path):
        parts = line.split()
        if len(parts) == 3:
            # Link-time optimization may add a suffix to a local name.
            symbols.setdefault(parts[2].split(".")[0], int(parts[0], 16))
    # Stage 24a3 (D64): the SGDK sprite engine is gone from the ROM; its DMA of the sprite table
    # would overwrite the screen's dots.
    if "SPR_update" in symbols:
        raise SystemExit(f"{symbols_path}: SPR_update is in the ROM (D64)")
    # Stage 29 (review of 24a3): the ROM's bss must end below 0xFFC300, where the RAM the screen counts
    # on for SGDK starts; in 0.24.8 it ended at 0xFFC0D2, about 560 bytes short.
    if "_bend" not in symbols or symbols["_bend"] & 0xFFFFFF >= 0xFFC300:
        raise SystemExit(f"{symbols_path}: the ROM's bss ends at {symbols.get('_bend', 0) & 0xFFFFFF:#x}, at or past 0xFFC300")
    for name in ("_stext", "_etext", "_edata", "percussionPcmSample", "M_BANK_0", "ENVELOPES", "ARP_ROWS", "PROGRAM_NAMES"):
        if name not in symbols:
            raise SystemExit(f"{symbols_path}: no symbol {name}")
    # SGDK copies .data from the image at _stext to RAM at start, so the file holds the table there.
    data_load = symbols["_stext"]
    table = symbols["percussionPcmSample"]
    if not RAM <= table < symbols["_edata"]:
        raise SystemExit(f"percussionPcmSample at {table:#x} is not in .data")
    # Stage 24: the bank's tables. The pointers to the FM voices and envelopes are .data, copied to
    # RAM at start, so the image holds them at their load address; the rows and names are .rodata.
    data = {}
    for name in ("M_BANK_0", "ENVELOPES"):
        if not RAM <= symbols[name] < symbols["_edata"]:
            raise SystemExit(f"{name} at {symbols[name]:#x} is not in .data")
        data[name] = data_load + symbols[name] - RAM
    for name in ("ARP_ROWS", "PROGRAM_NAMES"):
        if not symbols[name] < symbols["_etext"]:
            raise SystemExit(f"{name} at {symbols[name]:#x} is not in .rodata")
        data[name] = symbols[name]

    text = open(samples_path).read()
    files = dict(re.findall(r"static const PcmSample (\w+) = \{ pcm_(\w+),", text))
    body = re.search(r"percussionPcmSample\[128\]\s*=\s*\{(.*?)\};", text, re.S).group(1)
    body = re.sub(r"//[^\n]*", "", body)
    entries = [e.strip() for e in body.split(",") if e.strip()]
    if len(entries) != 128:
        raise SystemExit(f"expected 128 notes in percussionPcmSample, found {len(entries)}")
    names = []
    for entry in entries:
        if entry == "NULL":
            names.append("")
        else:
            names.append(files[entry.lstrip("&")].replace("_", ""))

    lines = [
        "// Generated by tools/gen_rom_map.py from the ROM build. Do not edit.",
        "#ifndef MDMI_ROM_MAP_H",
        "#define MDMI_ROM_MAP_H",
        f"#define ROM_PCM_TABLE 0x{data_load + table - RAM:06X}u",
        # SGDK copies the table to RAM at start: the running ROM reads it there (D39).
        f"#define ROM_PCM_TABLE_RAM 0x{table - RAM:04X}u",
        f"#define ROM_USED_END 0x{data_load + symbols['_edata'] - RAM:06X}u",
        f"#define ROM_FM_PRESETS 0x{data['M_BANK_0']:06X}u",
        f"#define ROM_ENVELOPES 0x{data['ENVELOPES']:06X}u",
        f"#define ROM_ARP_ROWS 0x{data['ARP_ROWS']:06X}u",
        f"#define ROM_PROGRAM_NAMES 0x{data['PROGRAM_NAMES']:06X}u",
    ]
    # Stage 24a2: the screen's tile patterns in the image, which reg_test compares with VRAM.
    for name in ("UI_TILES", "UI_TILES_B"):
        if not symbols.get(name, RAM) < symbols["_etext"]:
            raise SystemExit(f"{symbols_path}: no .rodata symbol {name}")
        lines.append(f"#define ROM_{name} 0x{symbols[name]:06X}u")
    # Stage 24a: where the screen's counters live in the 68000's RAM, for reg_test (rom-screen.md 10.4).
    for name in STATS:
        if not RAM <= symbols.get(name, 0) < RAM + 0x10000:
            raise SystemExit(f"{symbols_path}: no RAM symbol {name}")
        lines.append(f"#define ROM_{name.upper()} 0x{symbols[name] & 0xFFFFFF:06X}u")
    lines += [
        "static const char *const ROM_SAMPLE_NAMES[128] = {",
    ]
    for i in range(0, 128, 8):
        lines.append("\t" + " ".join(f'"{n}",' for n in names[i:i + 8]))
    lines += ["};", "#endif", ""]
    open(output, "w", newline="\n").write("\n".join(lines))


if __name__ == "__main__":
    main()
