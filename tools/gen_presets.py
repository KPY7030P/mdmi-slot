"""Generates src/presets_gm.h from the MDMI ROM's FM preset bank.

usage: gen_presets.py <third_party/mdmi/src/presets.c> <src/presets_gm.h>
"""
import re
import sys

NUM_OPS = 4
OP_FIELDS = 11


def main():
    source, output = sys.argv[1:3]
    text = open(source).read()

    presets = {}
    for name, body in re.findall(r"static const FmPreset (\w+)\s*=\s*\{(.*?)\};", text, re.S):
        numbers = [int(n) for n in re.findall(r"\d+", body)]
        if len(numbers) != 4 + NUM_OPS * OP_FIELDS:
            raise SystemExit(f"{name}: expected {4 + NUM_OPS * OP_FIELDS} values, found {len(numbers)}")
        presets[name] = numbers

    bank = re.search(r"const FmPreset\* M_BANK_0\[128\]\s*=\s*\{(.*?)\};", text, re.S).group(1)
    order = re.findall(r"&(\w+)", bank)
    if len(order) != 128:
        raise SystemExit(f"expected 128 presets in M_BANK_0, found {len(order)}")

    lines = [
        "// Generated by tools/gen_presets.py from the MDMI ROM's M_BANK_0. Do not edit.",
        "// Layout: algorithm, feedback, ams, fms, then for each of 4 operators:",
        "// multiple, detune, attack, rate scaling, decay, am, sustain level, sustain rate, release, total level, ssg-eg",
        f"static const uint8_t PRESETS_GM[128][{4 + NUM_OPS * OP_FIELDS}] = {{",
    ]
    for name in order:
        lines.append("\t{" + ", ".join(str(n) for n in presets[name]) + "},")
    lines.append("};")
    with open(output, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


main()
